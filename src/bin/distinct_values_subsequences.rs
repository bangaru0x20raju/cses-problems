#![allow(unused)]

use std::{fmt::Debug, io, str::FromStr};

fn read_number<T>() -> T
where
    T: FromStr,
    <T as FromStr>::Err: Debug,
{
    let mut number = String::new();
    io::stdin()
        .read_line(&mut number)
        .expect("Failed to read from stdin");
    number.trim().parse().expect("Failed to parse the input")
}

fn read_string() -> String {
    let mut line = String::new();
    io::stdin()
        .read_line(&mut line)
        .expect("Failed to read the string.");
    line
}

fn read_vector<T>() -> Vec<T>
where
    T: FromStr,
    <T as FromStr>::Err: Debug,
{
    let mut line = String::new();
    io::stdin()
        .read_line(&mut line)
        .expect("Failed to read the vector.");
    line.trim()
        .split_whitespace()
        .map(|x| x.parse().expect("Failed to parse element"))
        .collect()
}

fn main() {
    let n : i32 = read_number();
    let mut arr : Vec<u64> = read_vector();
    let mut unique_count = 1 as u32 ;
    arr.sort();
    let mut duplicate_count = 0 as u32;
    let mut prev = arr[0]; 
    for i in 1..n { 
        if prev!=arr[i as usize]{
            unique_count+=1;
            prev = arr[ i as usize];
            continue;
        }
        duplicate_count+=1;
    }    
}